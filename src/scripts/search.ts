// Search page: runs Pagefind (built into dist/pagefind by `npm run build`) in the browser.
interface PagefindResultData {
  url: string;
  excerpt: string;
  meta: { title?: string; category?: string };
}
interface PagefindModule {
  search(query: string): Promise<{ results: { data(): Promise<PagefindResultData> }[] }>;
}

const root = document.querySelector<HTMLElement>('[data-search-page]');
const form = root?.querySelector<HTMLFormElement>('form');
const input = root?.querySelector<HTMLInputElement>('input[name="q"]');
const status = root?.querySelector<HTMLElement>('[data-search-status]');
const list = root?.querySelector<HTMLElement>('[data-search-results]');

// In `astro dev` there is no pagefind bundle; the page shows a note instead.
if (root && form && input && status && list && !import.meta.env.DEV) {
  const base = root.dataset.base ?? '';
  let loader: Promise<PagefindModule> | null = null;
  let latest = 0;
  let timer = 0;

  const load = () => (loader ??= import(/* @vite-ignore */ `${base}/pagefind/pagefind.js`) as Promise<PagefindModule>);

  function renderItem(item: PagefindResultData, position: number): HTMLLIElement {
    const li = document.createElement('li');
    const num = document.createElement('span');
    num.className = 'index-num meta';
    num.setAttribute('aria-hidden', 'true');
    num.textContent = String(position).padStart(2, '0');
    const body = document.createElement('div');
    const link = document.createElement('a');
    link.className = 'index-link';
    link.href = base + (item.url.startsWith('/') ? item.url : `/${item.url}`);
    link.textContent = item.meta.title ?? item.url;
    body.append(link);
    if (item.meta.category) {
      const category = document.createElement('p');
      category.className = 'meta';
      category.textContent = item.meta.category;
      body.append(category);
    }
    const excerpt = document.createElement('p');
    excerpt.className = 'index-summary';
    excerpt.innerHTML = item.excerpt; // generated by Pagefind from our own pages; contains <mark>
    body.append(excerpt);
    li.append(num, body);
    return li;
  }

  async function run(raw: string): Promise<void> {
    const query = raw.trim();
    const mine = ++latest;
    list!.replaceChildren();
    if (!query) {
      status!.textContent = '';
      return;
    }
    status!.textContent = 'Searching…';
    try {
      const pagefind = await load();
      const found = await pagefind.search(query);
      const data = await Promise.all(found.results.slice(0, 20).map((r) => r.data()));
      if (mine !== latest) return;
      const total = found.results.length;
      status!.textContent = total === 0 ? `No results for “${query}”.` : `${total} result${total === 1 ? '' : 's'} for “${query}”.`;
      data.forEach((item, i) => list!.append(renderItem(item, i + 1)));
    } catch {
      if (mine === latest) status!.textContent = 'Search is not available. Run npm run build, then npm run preview.';
    }
  }

  function sync(query: string): void {
    const next = new URL(location.href);
    if (query.trim()) next.searchParams.set('q', query.trim());
    else next.searchParams.delete('q');
    history.replaceState(null, '', next);
    void run(query);
  }

  form.addEventListener('submit', (event) => {
    event.preventDefault();
    sync(input.value);
  });
  input.addEventListener('input', () => {
    window.clearTimeout(timer);
    timer = window.setTimeout(() => sync(input.value), 200);
  });

  const initial = new URLSearchParams(location.search).get('q') ?? '';
  input.value = initial;
  if (initial) void run(initial);
}
